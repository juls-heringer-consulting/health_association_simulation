/* =============================================================================
   102_meta_procedures.sql
   Helper procedures used by the Python loader and by all load procedures.
   CREATE OR ALTER makes every procedure re-runnable.
   ============================================================================= */
USE KVSim;
GO

-- Start a load batch and return its id.
CREATE OR ALTER PROCEDURE meta.usp_batch_start
    @note     NVARCHAR(400) = NULL,
    @batch_id INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO meta.load_batch (note) VALUES (@note);
    SET @batch_id = CAST(SCOPE_IDENTITY() AS INT);   -- id generated by the INSERT above
END
GO

CREATE OR ALTER PROCEDURE meta.usp_batch_end
    @batch_id INT,
    @status   VARCHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE meta.load_batch
       SET status = @status, finished_at = SYSDATETIME()
     WHERE batch_id = @batch_id;
END
GO

CREATE OR ALTER PROCEDURE meta.usp_file_log
    @batch_id        INT,
    @source_name     VARCHAR(60),
    @file_name       NVARCHAR(260),
    @file_sha256     CHAR(64),
    @file_size_bytes BIGINT,
    @target_table    NVARCHAR(128),
    @rows_loaded     INT
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO meta.load_file (batch_id, source_name, file_name, file_sha256, file_size_bytes, target_table, rows_loaded)
    VALUES (@batch_id, @source_name, @file_name, @file_sha256, @file_size_bytes, @target_table, @rows_loaded);
END
GO

CREATE OR ALTER PROCEDURE meta.usp_step_start
    @batch_id  INT,
    @step_name NVARCHAR(128),
    @step_id   INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO meta.load_step (batch_id, step_name) VALUES (@batch_id, @step_name);
    SET @step_id = CAST(SCOPE_IDENTITY() AS INT);
END
GO

CREATE OR ALTER PROCEDURE meta.usp_step_end
    @step_id       INT,
    @status        VARCHAR(10),
    @rows_affected INT = NULL,
    @message       NVARCHAR(4000) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE meta.load_step
       SET status = @status, finished_at = SYSDATETIME(), rows_affected = @rows_affected, message = @message
     WHERE step_id = @step_id;
END
GO

-- The most recent successful staging batch (used as default by the load procedures).
CREATE OR ALTER FUNCTION meta.fn_latest_batch_id ()
RETURNS INT
AS
BEGIN
    RETURN (SELECT MAX(batch_id) FROM meta.load_batch WHERE status = 'OK');
END
GO

/* Adds or updates a description (extended property MS_Description) on a table or column.
   These descriptions are the single source of truth for the data dictionary:
   SSMS shows them in the table designer, and docs/data_dictionary.md is generated from them. */
CREATE OR ALTER PROCEDURE meta.usp_describe
    @schema      SYSNAME,
    @table       SYSNAME,
    @column      SYSNAME = NULL,
    @description NVARCHAR(3750)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @level2type VARCHAR(10) = CASE WHEN @column IS NULL THEN NULL ELSE 'COLUMN' END;
    IF EXISTS (SELECT 1 FROM sys.fn_listextendedproperty(N'MS_Description', 'SCHEMA', @schema, 'TABLE', @table, @level2type, @column))
        EXEC sys.sp_updateextendedproperty @name = N'MS_Description', @value = @description,
             @level0type = 'SCHEMA', @level0name = @schema, @level1type = 'TABLE', @level1name = @table,
             @level2type = @level2type, @level2name = @column;
    ELSE
        EXEC sys.sp_addextendedproperty @name = N'MS_Description', @value = @description,
             @level0type = 'SCHEMA', @level0name = @schema, @level1type = 'TABLE', @level1name = @table,
             @level2type = @level2type, @level2name = @column;
END
GO

/* Drops every table of a schema, including foreign keys that point INTO the schema
   from elsewhere. Used at the start of the stg/core/mart DDL scripts so that they
   can be re-run in any state. Only ever call it for stg, core or mart. */
CREATE OR ALTER PROCEDURE meta.usp_drop_tables
    @schema SYSNAME
AS
BEGIN
    SET NOCOUNT ON;
    IF @schema NOT IN (N'stg', N'core', N'mart')
        THROW 50001, 'meta.usp_drop_tables may only be used for stg, core or mart.', 1;

    DECLARE @sql NVARCHAR(MAX) = N'';

    SELECT @sql += N'ALTER TABLE ' + QUOTENAME(OBJECT_SCHEMA_NAME(fk.parent_object_id)) + N'.'
                 + QUOTENAME(OBJECT_NAME(fk.parent_object_id)) + N' DROP CONSTRAINT ' + QUOTENAME(fk.name) + N';' + NCHAR(10)
    FROM sys.foreign_keys AS fk
    WHERE OBJECT_SCHEMA_NAME(fk.parent_object_id) = @schema
       OR OBJECT_SCHEMA_NAME(fk.referenced_object_id) = @schema;

    SELECT @sql += N'DROP TABLE ' + QUOTENAME(s.name) + N'.' + QUOTENAME(t.name) + N';' + NCHAR(10)
    FROM sys.tables AS t
    JOIN sys.schemas AS s ON s.schema_id = t.schema_id
    WHERE s.name = @schema;

    EXEC sys.sp_executesql @sql;
END
GO
