"""Copy the specs of all Deneb visuals in the Power BI report to dashboard_site/deneb_specs.js.

The static site renders the exact same Vega / Vega-Lite specifications as the Deneb visuals in
powerbi_report (pages 'Fachgruppe Growth' and 'Vega Showcase'), so both show the same charts.
For every visual of type Deneb the script reads the PBIR properties `provider`, `version`,
`jsonSpec` and `jsonConfig`; nothing in the report is changed.

Usage (from the project root):
    .venv\\Scripts\\python.exe python\\export_deneb_specs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PAGES = PROJECT_ROOT / "powerbi_report" / "KVSim_Analysis.Report" / "definition" / "pages"
OUT_FILE = PROJECT_ROOT / "dashboard_site" / "deneb_specs.js"
DENEB = "deneb7E15AEF80B9E4D4F8E12924291ECE89A"


def deneb_text(props: dict, name: str) -> str:
    """Deneb stores text properties as Power BI literals: '...' with single quotes doubled."""
    value = props[name]["expr"]["Literal"]["Value"]
    if not (value.startswith("'") and value.endswith("'")):
        raise ValueError(f"unexpected literal for {name}: {value[:40]}")
    return value[1:-1].replace("''", "'")


def main() -> int:
    specs: dict = {}
    for visual_file in sorted(PAGES.glob("*/visuals/*/visual.json")):
        visual = json.loads(visual_file.read_text(encoding="utf-8"))
        if visual["visual"].get("visualType") != DENEB:
            continue
        page = json.loads((visual_file.parents[2] / "page.json").read_text(encoding="utf-8"))
        props = visual["visual"]["objects"]["vega"][0]["properties"]
        specs[visual["name"]] = {
            "page": page["displayName"],
            "provider": deneb_text(props, "provider"),
            "version": deneb_text(props, "version"),
            "renderMode": deneb_text(props, "renderMode") if "renderMode" in props else "svg",
            "spec": json.loads(deneb_text(props, "jsonSpec")),
            "config": json.loads(deneb_text(props, "jsonConfig")),
        }
    if not specs:
        raise SystemExit("no Deneb visuals found")
    OUT_FILE.write_text(
        "// Generated by python/export_deneb_specs.py from the Deneb visuals in powerbi_report.\n"
        "// Do not edit by hand.\n"
        f"window.KVSIM_DENEB = {json.dumps(specs, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8")
    print(f"wrote {OUT_FILE.relative_to(PROJECT_ROOT)} ({OUT_FILE.stat().st_size / 1024:.0f} KB): "
          + ", ".join(f"{k} ({v['provider']}, page '{v['page']}')" for k, v in specs.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
