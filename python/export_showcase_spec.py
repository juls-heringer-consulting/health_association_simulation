"""Copy the Vega spec of the Power BI 'Vega Showcase' visual to dashboard_site/showcase_spec.js.

The static site renders the exact same specification as the Deneb visual in the Power BI report,
so the two can be compared side by side (for example SVG vs. canvas rendering). The spec is read
from the visual's PBIR file (Deneb properties `jsonSpec` and `jsonConfig`); nothing is changed.

Usage (from the project root):
    .venv\\Scripts\\python.exe python\\export_showcase_spec.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
VISUAL = (PROJECT_ROOT / "powerbi_report" / "KVSim_Analysis.Report" / "definition" / "pages"
          / "p8vegashowcase00000h" / "visuals" / "tss_year_clock" / "visual.json")
OUT_FILE = PROJECT_ROOT / "dashboard_site" / "showcase_spec.js"


def deneb_text(props: dict, name: str) -> str:
    """Deneb stores text properties as Power BI literals: '...' with single quotes doubled."""
    value = props[name]["expr"]["Literal"]["Value"]
    if not (value.startswith("'") and value.endswith("'")):
        raise ValueError(f"unexpected literal for {name}: {value[:40]}")
    return value[1:-1].replace("''", "'")


def main() -> int:
    visual = json.loads(VISUAL.read_text(encoding="utf-8"))
    props = visual["visual"]["objects"]["vega"][0]["properties"]
    payload = {
        "provider": deneb_text(props, "provider"),
        "version": deneb_text(props, "version"),
        "spec": json.loads(deneb_text(props, "jsonSpec")),
        "config": json.loads(deneb_text(props, "jsonConfig")),
    }
    if payload["provider"] != "vega":
        raise ValueError("the showcase page expects a Vega (not Vega-Lite) spec")
    OUT_FILE.write_text(
        "// Generated by python/export_showcase_spec.py from the Deneb visual 'tss_year_clock'\n"
        "// (powerbi_report, page 'Vega Showcase'). Do not edit by hand.\n"
        f"window.KVSIM_SHOWCASE = {json.dumps(payload, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8")
    print(f"wrote {OUT_FILE.relative_to(PROJECT_ROOT)} ({OUT_FILE.stat().st_size / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
